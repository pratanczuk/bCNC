"""Consistent 20 px outline icons, drawn from local vector coordinates."""
def paint(draw, name, x, y, color):
    def line(points):
        draw.line([(x+a*2,y+b*2) for a,b in points], fill=color, width=3, joint='curve')
    paths = {
        'Select': [[(4,2),(4,17),(8,13),(12,19),(15,17),(11,11),(17,10),(4,2)]],
        'Pan': [[(4,11),(4,6),(7,6),(7,2),(10,2),(10,6),(13,6),(13,3),(16,3),(16,8),(18,8),(18,14),(14,19),(7,19),(2,13),(2,10),(4,11)]],
        'Move': [[(10,1),(10,19)],[(1,10),(19,10)],[(7,4),(10,1),(13,4)],[(7,16),(10,19),(13,16)],[(4,7),(1,10),(4,13)],[(16,7),(19,10),(16,13)]],
        'Fit mat': [[(7,2),(2,2),(2,7)],[(13,2),(18,2),(18,7)],[(2,13),(2,18),(7,18)],[(13,18),(18,18),(18,13)]],
        'Undo': [[(7,3),(2,8),(7,13)],[(2,8),(12,8),(17,11),(17,17)]],
        'Redo': [[(13,3),(18,8),(13,13)],[(18,8),(8,8),(3,11),(3,17)]],
        'Grid': [[(2,2),(18,2),(18,18),(2,18),(2,2)],[(2,8),(18,8)],[(2,13),(18,13)],[(8,2),(8,18)],[(13,2),(13,18)]],
        'Panel': [[(2,2),(18,2),(18,18),(2,18),(2,2)],[(12,2),(12,18)]]}
    for path in paths.get(name, []):
        line(path)
